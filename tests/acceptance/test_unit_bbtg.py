def test_md_to_json_keeps_headings_and_tables_only():
    data = bbtg.md_to_json(MD)
    headings = [(s["level"], s["heading"]) for s in data["sections"]]
    assert headings == [(1, "OwnerRestController Dependency Tree"), (2, "엔드포인트 목록"), (2, "의존성 트리"),
                        (3, "getAllOwners (GET /api/owners)"), (2, "DB 테이블 요약")]
    endpoints = data["sections"][1]["tables"][0]
    assert endpoints["columns"] == ["Method", "Path", "Handler Method"]
    assert endpoints["rows"] == [["GET", "/api/owners", "getAllOwners"], ["POST", "/api/owners", "createOwner"]]
    assert data["sections"][3]["tables"] == []  # 코드 블록 안의 표 모양은 버린다
    assert data["sections"][4]["tables"] == [{"columns": ["테이블명", "연산"], "rows": []}]
    assert "2026" not in json.dumps(data) and "Generated by" not in json.dumps(data)


def test_service_methods_takes_di_and_service_not_repository():
    tree = "├── [DI] ReservationService.create\n├── [Repository] OwnerRepository.save\n├── [Static] ReservationResponse.from\n" \
           "├── [Service] PetService.rename\n├── [DI] ReservationService.create\n"
    assert bbtg.service_methods(tree) == [("ReservationService", "create"), ("PetService", "rename")]


def test_enumerate_controllers_sorted_and_relative(tmp_path):
    base = tmp_path / "src" / "main" / "java" / "p"
    base.mkdir(parents=True)
    (base / "B.java").write_text("package p;\n@RestController\nclass B {}\n")
    (base / "A.java").write_text("package p;\n  @RestController(\"x\")\nclass A {}\n")
    (base / "C.java").write_text("package p;\n// @RestController in a comment\n@Controller class C {}\n")
    (base / "D.java").write_text("package p;\n@RestControllerAdvice class D {}\n")
    assert bbtg.enumerate_controllers(tmp_path, "src/main/java") == ["src/main/java/p/A.java", "src/main/java/p/B.java"]


def test_parse_first_json_ignores_trailing_lines_and_midtext_brackets():
    assert bbtg._parse_first_json('{"a": 1}\n[Artifact saved] x\n') == {"a": 1}
    assert bbtg._parse_first_json("✅ saved: 범위([]) 밖\n") is None
    assert bbtg._parse_first_json("") is None


def test_prune_removes_unlisted_keys_and_counts_only_valued_paths():
    schema = {"type": "object", "additionalProperties": False, "properties": {
        "keep": {"type": "string"},
        "items": {"type": "array", "items": {"type": "object", "additionalProperties": False,
                                             "properties": {"name": {"type": "string"}}}},
        "dyn": {"type": "object", "patternProperties": {"^.+$": {"type": "integer"}}, "additionalProperties": False}}}
    removed: Counter = Counter()
    value = {"keep": "k", "secret": "s", "empty": "", "items": [{"name": "a", "source": "code"}, {"name": "b", "source": "more"}],
             "dyn": {"x": 1, "y": 2}}
    pruned = bbtg.prune(value, schema, schema, "", removed)
    assert pruned == {"keep": "k", "items": [{"name": "a"}, {"name": "b"}], "dyn": {"x": 1, "y": 2}}
    assert dict(removed) == {"secret": 1, "items[].source": 2}  # 빈 값("empty")은 세지 않는다


def test_relativize_handles_resolved_variants_and_exact_root():
    roots = ["/private/tmp/x/src", "/tmp/x/src"]
    data = {"p": "/private/tmp/x/src/a/B.java", "q": "/tmp/x/src", "r": "see /tmp/x/src/c", "n": 3}
    assert bbtg._relativize(data, roots) == {"p": "a/B.java", "q": ".", "r": "see c", "n": 3}


def test_absolute_path_guard():
    assert bbtg._find_absolute({"a": ["ok", "/Users/me/x"]}) == ".a[1]"
    assert bbtg._find_absolute({"a": "src/main/java/Users/x.java"}) is None


def _write_raw(raw: Path, calls: list[dict], stdout: dict[str, object], sut_root: Path) -> None:
    (raw / "stdout").mkdir(parents=True)
    for name, payload in stdout.items():
        (raw / "stdout" / f"{name}.json").write_text(json.dumps(payload))
    (raw / "calls.json").write_text(json.dumps({"calls": calls}))
    (raw / "meta.json").write_text(json.dumps({"sutRoot": str(sut_root)}))


def test_sanitize_skips_failed_calls_and_reports_leaks(tmp_path):
    sut_root = tmp_path / "checkout"
    raw = tmp_path / "raw"
    calls = [
        {"id": "inspect-stack", "skill": "inspect-stack", "key": ".", "rc": 0, "stdout": "stdout/inspect-stack.json", "artifacts": []},
        {"id": "inspect-auth", "skill": "inspect-auth", "key": ".", "rc": 2, "stdout": None, "artifacts": []},
        {"id": "plan-tests-A.b", "skill": "plan-tests", "key": "A.b", "rc": 0, "stdout": "stdout/plan.json", "artifacts": []},
    ]
    stack = {"project_info": {"name": "n"}, "analysis_meta": {"timestamp": "2026-01-01T00:00:00Z", "scan_duration_ms": 5, "scanned_files": 4}}
    plan = {"class": "A", "method": "b", "test_cases": [{"id": "x", "condition": f"{sut_root}/leak"}], "artifact_path": ".bbtg/x.md"}
    _write_raw(raw, calls, {"inspect-stack": stack, "plan": plan}, sut_root)
    result = bbtg.sanitize(raw, tmp_path / "clean")
    assert result.written == ["inspect-stack.json", "plan-tests.json"]  # 실패한 inspect-auth는 파일이 없다
    clean = json.loads((tmp_path / "clean" / "inspect-stack.json").read_text())
    assert clean["results"][0]["data"]["analysis_meta"] == {"scanned_files": 4}
    assert result.removed_counts["inspect-stack:analysis_meta.timestamp"] == 1
    assert result.removed_counts["plan-tests:artifact_path"] == 1
    # SUT 루트 아래 절대 경로는 상대화된다(누수가 아니다)
    plan_clean = json.loads((tmp_path / "clean" / "plan-tests.json").read_text())
    assert plan_clean["results"][0]["data"]["test_cases"][0]["condition"] == "leak"
    assert not (tmp_path / "clean" / "inspect-auth.json").exists()


def test_sanitize_rejects_foreign_absolute_path(tmp_path):
    sut_root = tmp_path / "checkout"
    raw = tmp_path / "raw"
    calls = [{"id": "plan-tests-A.b", "skill": "plan-tests", "key": "A.b", "rc": 0, "stdout": "stdout/plan.json", "artifacts": []}]
    plan = {"class": "A", "method": "b", "test_cases": [{"id": "x", "condition": "/Users/someone/else/Foo.java"}]}
    _write_raw(raw, calls, {"plan": plan}, sut_root)
    result = bbtg.sanitize(raw, tmp_path / "clean")
    assert "plan-tests.json" not in result.written and any("절대 경로" in e for e in result.errors)
    assert not (tmp_path / "clean" / "plan-tests.json").exists()
